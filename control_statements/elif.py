day = input("Enter day : ")

if day == "Monday" or day == "Mon" :
    print("Week started")
elif day == "Friday" or day == "Fri" :
    print("Weekend is coming")
elif day == "Saturday" or day == "Sat" :
    print("Weekend Started")
elif day == "Sunday" or day == "Sun" : 
    print("Relax, it's Sunday")
else :
    print("Just another day")